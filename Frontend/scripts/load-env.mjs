import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(rootDir, 'src/environments/env.values.ts');
const requiredKeys = ['COGNITO_AUTHORITY', 'COGNITO_CLIENT_ID'];

const values = {
  ...parseEnvFile(resolve(rootDir, '.env')),
};

for (const key of requiredKeys) {
  if (process.env[key]) {
    values[key] = process.env[key];
  }
}

const missing = requiredKeys.filter((key) => !values[key]);
if (missing.length > 0) {
  throw new Error(
    `Missing ${missing.join(', ')}. Set them in Frontend/.env locally, or as GitHub Actions secrets for the build.`,
  );
}

const serialized = requiredKeys
  .map((key) => `  ${key}: ${JSON.stringify(values[key])},`)
  .join('\n');

writeFileSync(
  outputPath,
  `/**
 * Generated by scripts/load-env.mjs.
 * Do not edit this file by hand.
 */
export const env = {
${serialized}
};
`,
  'utf8',
);

console.log(`Wrote Cognito settings to ${outputPath}`);

function parseEnvFile(filePath) {
  if (!existsSync(filePath)) {
    return {};
  }

  const parsed = {};
  for (const rawLine of readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) {
      continue;
    }

    const separator = line.indexOf('=');
    if (separator <= 0) {
      continue;
    }

    const key = line.slice(0, separator).trim();
    let value = line.slice(separator + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    parsed[key] = value;
  }

  return parsed;
}
